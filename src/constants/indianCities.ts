export const cityLabel = (c: City) => `${c.name}, ${c.state}`;

// Districts whose name differs from the city's (Circles > Discover). Everything else: district = city.
const DISTRICT_OF: Record<string, string> = {
  Secunderabad: 'Hyderabad',
  Hanamkonda: 'Hanumakonda',
  Ramagundam: 'Peddapalli',
  Bhadrachalam: 'Bhadradri Kothagudem',
  Kothagudem: 'Bhadradri Kothagudem',
  Rajahmundry: 'East Godavari',
  Bengaluru: 'Bengaluru Urban',
  Noida: 'Gautam Buddha Nagar',
  Howrah: 'Howrah',
};

// District of a bundled city (for the profile district when location is off)
export const cityDistrict = (c: City): string => c.district || DISTRICT_OF[c.name] || c.name;

// 'Bhubaneswar, Odisha' / 'bhubaneswar' -> the city; null when not in the list
export const findCity = (label?: string | null): City | null => {
  const q = (label || '').trim().toLowerCase();
  if (!q) return null;
  const name = q.split(',')[0].trim();
  return INDIAN_CITIES.find(c => cityLabel(c).toLowerCase() === q) || INDIAN_CITIES.find(c => c.name.toLowerCase() === name) || null;
};

// Prefix matches first, then anywhere in the name or state
export const searchCities = (text: string, max = 30): City[] => {
  const q = text.trim().toLowerCase();
  if (!q) return INDIAN_CITIES.slice(0, max);
  const starts = INDIAN_CITIES.filter(c => c.name.toLowerCase().startsWith(q));
  const rest = INDIAN_CITIES.filter(c => !starts.includes(c) && cityLabel(c).toLowerCase().includes(q));
  return [...starts, ...rest].slice(0, max);
};

export const birthPlaceOf = (label?: string | null): BirthPlace | null => {
  const c = findCity(label);
  return c ? { name: cityLabel(c), lat: c.lat, lng: c.lng, tzMinutes: 330 } : null;
};
