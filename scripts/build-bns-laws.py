#!/usr/bin/env python3
# Builds src/data/laws/bns.generated.ts from scripts/bns-schedule.json.
# bns-schedule.json = the First Schedule of the Bharatiya Nagarik Suraksha Sanhita, 2023 (classification
# of offences under the BNS: offence, punishment, cognizable, bailable, court) as published by NCRB /
# MHA at https://www.ncrb.mha.gov.in/uploads/SankalanPortal/ScheduleBNSS.html, plus the old IPC
# section(s) from NCRB's "Corresponding Section Table of BNS with Repealed Act"
# (https://www.ncrb.mha.gov.in/uploads/SankalanPortal/DownloadPDF/BNS2023.pdf). Text is kept as published.
import json, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = json.load(open(os.path.join(root, 'scripts', 'bns-schedule.json')))
out = []
for r in rows:
    out.append([r['sec'], r['title'], r['offence'], r['punishment'], r['cog'], r['bail'], r['court'], ','.join(r['ipc'])])
body = '[\n' + ''.join('  ' + json.dumps(r, ensure_ascii=False) + ',\n' for r in out) + ']'
ts = ('/* eslint-disable */\n// GENERATED by scripts/build-bns-laws.py from scripts/bns-schedule.json. Do not edit by hand.\n'
      '// Every BNS offence row of the First Schedule to the BNSS, 2023 (official classification of offences):\n'
      '// [section, section title, offence, punishment, cognizable, bailable, court, old IPC section(s)].\n'
      '// A section ending in "~" is a second line of the same section in the Schedule (another case of it).\n'
      'export type BnsRow = [string, string, string, string, string, string, string, string];\n'
      f'export const BNS_ROWS: BnsRow[] = {body};\n')
open(os.path.join(root, 'src', 'data', 'laws', 'bns.generated.ts'), 'w').write(ts)
print(len(out), 'rows')
