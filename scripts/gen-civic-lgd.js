#!/usr/bin/env node
// Writes server/worker/src/civic/lgd.js: the LGD (Local Government Directory) codes of every district
// and sub-district (mandal / taluk / tehsil ...) of the app's location picker (src/data/locations/india.json),
// keyed by the same slugs the app sends (districtSlug / normDistrict). OpenStreetMap tags Indian
// boundaries with these codes (ref:LGD:district, ref:LGD:subdistrict), so the Worker can ask Overpass
// for the EXACT district / mandal boundary instead of guessing it by name.
// Run after updating india.json:  node scripts/gen-civic-lgd.js
// __tests__/civicHospScope.test.ts checks the file is up to date.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const slug = v =>
  String(v || '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 40);

const india = JSON.parse(fs.readFileSync(path.join(ROOT, 'src/data/locations/india.json'), 'utf8'));
const lines = india.states.map(st => {
  const ds = {};
  st.d.forEach(d => {
    const subs = {};
    (d.s || []).forEach(([c, n]) => {
      const k = slug(n);
      if (k && !(k in subs)) subs[k] = c;
    });
    const k = slug(d.n);
    if (k && !(k in ds)) ds[k] = [d.c, d.n, subs];
  });
  return `  ${st.c}: ${JSON.stringify({ lgd: st.lgd, d: ds })},`;
});
const out = `// GENERATED by scripts/gen-civic-lgd.js from src/data/locations/india.json (${india.source}): do not edit.
// state code -> { lgd: state LGD code, d: { district slug: [district LGD code, name, { mandal slug: sub-district LGD code }] } }
export const LGD = {
${lines.join('\n')}
};
`;
fs.writeFileSync(path.join(ROOT, 'server/worker/src/civic/lgd.js'), out);
console.log('wrote server/worker/src/civic/lgd.js', out.length, 'bytes');
