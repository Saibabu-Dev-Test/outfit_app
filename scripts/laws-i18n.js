#!/usr/bin/env node
// Generates the plain-language layer of the Laws tab with Gemini (repo secret GEMINI_API_KEY, run by
// .github/workflows/laws-i18n.yml, never with a key in git):
//   src/data/laws/plain.en.ts   short plain-English title + simple explanation per section
//   src/data/laws/plain.te.ts   Telugu: title, explanation, punishment in simple words
//   src/data/laws/plain.hi.ts   Hindi: same
// Keyed by the LawSection id from src/services/laws.ts (every BNS Schedule row + every curated
// section). Resumable: sections already in the files are skipped, so a re-run only fills gaps.
// The model may only restate the given official text in simple words (no new facts); the app says
// the official legal text prevails.
//   GEMINI_API_KEY=... node scripts/laws-i18n.js [--limit N] [--batch 12]
const fs = require('fs');
const path = require('path');
const ts = require('typescript');

const ROOT = path.join(__dirname, '..');
const OUT = { en: 'src/data/laws/plain.en.ts', te: 'src/data/laws/plain.te.ts', hi: 'src/data/laws/plain.hi.ts' };
const MODELS = ['gemini-3.6-flash', 'gemini-3.5-flash-lite', 'gemini-3.8-flash', 'gemini-flash-latest', 'gemini-3.1-flash-lite'];
const ENDPOINT = 'https://generativelanguage.googleapis.com/v1beta/models';

// Load TS modules (laws.ts and its data) without a build step
require.extensions['.ts'] = (module, filename) => {
  const src = fs.readFileSync(filename, 'utf8');
  const out = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true } });
  module._compile(out.outputText, filename);
};

const arg = (name, dflt) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > 0 ? Number(process.argv[i + 1]) : dflt;
};

// Existing map from a generated file (the JSON between the markers)
function readMap(file) {
  try {
    const s = fs.readFileSync(path.join(ROOT, file), 'utf8');
    const a = s.indexOf('/*JSON*/') + 8;
    const b = s.lastIndexOf('/*END*/');
    return a > 7 && b > a ? JSON.parse(s.slice(a, b)) : {};
  } catch (e) {
    return {};
  }
}

function writeMap(lang, map) {
  const names = { en: 'English', te: 'Telugu', hi: 'Hindi' };
  const sorted = {};
  Object.keys(map)
    .sort()
    .forEach(k => (sorted[k] = map[k]));
  const body = [
    '/* eslint-disable */',
    `// GENERATED by scripts/laws-i18n.js (Gemini) - ${names[lang]} plain-language text for the Laws tab.`,
    '// Keyed by LawSection id. t = short plain title, x = simple explanation, p = punishment in simple words.',
    '// AI-written aid only: the official legal text (India Code) prevails. Re-run the workflow to fill gaps.',
    "import type { PlainText } from './plainTypes';",
    `export const PLAIN_${lang.toUpperCase()}: Record<string, PlainText> = /*JSON*/${JSON.stringify(sorted, null, 1)}/*END*/;`,
    '',
  ].join('\n');
  fs.writeFileSync(path.join(ROOT, OUT[lang]), body);
}

const clean = (v, max) => (typeof v === 'string' ? v.replace(/\s+/g, ' ').trim().slice(0, max) : '');

function prompt(batch) {
  const items = batch.map(s => ({
    id: s.id,
    act: s.act,
    section: s.section,
    legalTitle: s.title,
    offence: s.summary,
    punishment: s.punishment,
    meaning: s.meaning || undefined,
  }));
  return [
    'You help ordinary people in India understand law sections. For EACH item below write:',
    '- en.t: a short plain-English title (max 8 words) that a non-lawyer understands (e.g. "Cheating to get money or property").',
    '- en.x: 1-2 simple English sentences: what this section is about / what act is an offence.',
    '- te.t, te.x, te.p and hi.t, hi.x, hi.p: the same title and explanation in simple everyday Telugu and Hindi (native script), and p = the punishment in simple words.',
    'Use ONLY the facts in the given text (offence, punishment, meaning). Do not add new facts, numbers, examples or advice. Keep section numbers and amounts exactly.',
    'Reply with ONLY a JSON object keyed by id: {"<id>":{"en":{"t":"","x":""},"te":{"t":"","x":"","p":""},"hi":{"t":"","x":"","p":""}}}',
    JSON.stringify(items),
  ].join('\n');
}

const sleep = ms => new Promise(r => setTimeout(r, ms));

async function gemini(text, key) {
  let last = 'no model answered';
  for (const model of MODELS) {
    for (let attempt = 0; attempt < 3; attempt++) {
      let res;
      try {
        res = await fetch(`${ENDPOINT}/${model}:generateContent`, {
          method: 'POST',
          headers: { 'content-type': 'application/json', 'x-goog-api-key': key },
          body: JSON.stringify({
            contents: [{ role: 'user', parts: [{ text }] }],
            generationConfig: { temperature: 0.1, maxOutputTokens: 32000, responseMimeType: 'application/json' },
          }),
        });
      } catch (e) {
        last = `network: ${e.message}`;
        await sleep(3000);
        continue;
      }
      if (res.status === 429 || res.status >= 500) {
        last = `${model}: http ${res.status}`;
        await sleep(15000 * (attempt + 1));
        continue;
      }
      if (res.status === 404) {
        last = `${model}: 404`;
        break;
      }
      if (!res.ok) {
        throw new Error(`${model}: http ${res.status} ${(await res.text()).slice(0, 200)}`);
      }
      const j = await res.json();
      const out = ((j.candidates && j.candidates[0] && j.candidates[0].content && j.candidates[0].content.parts) || []).map(p => p.text || '').join('');
      try {
        return { model, data: JSON.parse(out.replace(/```(?:json)?/g, '').trim()) };
      } catch (e) {
        last = `${model}: unreadable JSON`;
        break;
      }
    }
  }
  throw new Error(last);
}

async function main() {
  const key = (process.env.GEMINI_API_KEY || '').trim();
  if (!key) {
    console.error('GEMINI_API_KEY not set');
    process.exit(1);
  }
  const { allSections } = require(path.join(ROOT, 'src/services/laws.ts'));
  const sections = allSections();
  const maps = { en: readMap(OUT.en), te: readMap(OUT.te), hi: readMap(OUT.hi) };
  const todo = sections.filter(s => !(maps.en[s.id] && maps.te[s.id] && maps.hi[s.id]));
  const limit = arg('limit', todo.length);
  const size = arg('batch', 12);
  console.log(`sections ${sections.length}, missing ${todo.length}, doing ${Math.min(limit, todo.length)}`);
  let done = 0;
  let failed = 0;
  for (let i = 0; i < Math.min(limit, todo.length); i += size) {
    const batch = todo.slice(i, Math.min(i + size, limit));
    try {
      const { model, data } = await gemini(prompt(batch), key);
      batch.forEach(s => {
        const r = data && data[s.id];
        if (!r) return;
        const en = { t: clean(r.en && r.en.t, 80), x: clean(r.en && r.en.x, 400) };
        const te = { t: clean(r.te && r.te.t, 120), x: clean(r.te && r.te.x, 600), p: clean(r.te && r.te.p, 400) };
        const hi = { t: clean(r.hi && r.hi.t, 120), x: clean(r.hi && r.hi.x, 600), p: clean(r.hi && r.hi.p, 400) };
        if (en.t) maps.en[s.id] = en;
        if (te.t) maps.te[s.id] = te;
        if (hi.t) maps.hi[s.id] = hi;
        done += 1;
      });
      console.log(`batch ${i / size + 1}: ${batch.length} via ${model}, total ${done}`);
    } catch (e) {
      failed += batch.length;
      console.log(`batch ${i / size + 1} failed: ${e.message}`);
      if (/http 40[013]/.test(e.message)) break; // bad key / request: stop
    }
    // save after every batch so a timeout keeps the progress
    ['en', 'te', 'hi'].forEach(l => writeMap(l, maps[l]));
    await sleep(4000);
  }
  ['en', 'te', 'hi'].forEach(l => writeMap(l, maps[l]));
  console.log(`done ${done}, failed ${failed}; files: ${Object.values(OUT).join(', ')}`);
  console.log(`coverage: en ${Object.keys(maps.en).length}, te ${Object.keys(maps.te).length}, hi ${Object.keys(maps.hi).length} of ${sections.length}`);
}

main().catch(e => {
  console.error(e);
  process.exit(1);
});
