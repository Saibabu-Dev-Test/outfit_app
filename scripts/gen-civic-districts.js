#!/usr/bin/env node
// Writes server/worker/src/civic/districts.js: the districts of the app's bundled cities
// (src/constants/indianCities.ts, cityDistrict) per state code (src/constants/indiaStates.ts), so the
// civic research cron can fill those districts before anyone opens them (prefill = instant answers).
// Run after changing the city list:  node scripts/gen-civic-districts.js
// __tests__/civicFast.test.ts checks the file is up to date.
const fs = require('fs');
const path = require('path');
const ts = require('typescript');

require.extensions['.ts'] = (module, filename) => {
  const src = fs.readFileSync(filename, 'utf8');
  const out = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true } });
  module._compile(out.outputText, filename);
};

const ROOT = path.join(__dirname, '..');
const { INDIAN_CITIES, cityDistrict } = require(path.join(ROOT, 'src/constants/indianCities.ts'));
const { INDIA_STATES } = require(path.join(ROOT, 'src/constants/indiaStates.ts'));

const slug = v =>
  String(v || '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 40);

const codeOf = name => {
  const n = name.toLowerCase();
  const s = INDIA_STATES.find(x => x.name.toLowerCase() === n) || INDIA_STATES.find(x => x.name.toLowerCase().startsWith(n));
  return s ? s.code : null;
};

const byState = {};
INDIAN_CITIES.forEach(c => {
  const code = codeOf(c.state);
  if (!code) return;
  const d = slug(cityDistrict(c));
  byState[code] = byState[code] || [];
  if (d && !byState[code].includes(d)) byState[code].push(d);
});
const codes = Object.keys(byState).sort();
const body = codes.map(c => `  ${c}: ${JSON.stringify(byState[c])},`).join('\n');
const out = `// GENERATED by scripts/gen-civic-districts.js from src/constants/indianCities.ts: do not edit.
// District slugs (same rules as normDistrict) the civic cron researches ahead of time, per state.
export const SEED_DISTRICTS = {
${body}
};
`;
fs.writeFileSync(path.join(ROOT, 'server/worker/src/civic/districts.js'), out);
console.log(`wrote ${codes.length} states, ${codes.reduce((n, c) => n + byState[c].length, 0)} districts`);
